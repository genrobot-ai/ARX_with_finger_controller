// 最基本的DMA发送函数
void UART_Transmit_DMA(uint8_t *data, uint16_t length)
{
    // 等待上一次发送完成
    while(HAL_UART_GetState(&huart1) == HAL_UART_STATE_BUSY_TX);
    
    // 开始DMA发送
    HAL_UART_Transmit_DMA(&huart1, data, length);
}
/**
  * @brief  使用DMA发送数据包（HAL库版本）
  * @param  data: 要发送的数据指针   在函数中自动的添加帧头帧尾 das\r\n
  * @param  length: 数据长度
  * @retval HAL status: HAL_OK表示成功，其他表示失败
  */

HAL_StatusTypeDef DMA_Send_Packet(uint8_t* data, uint16_t length)
{
    // 检查参数有效性
    if (data == NULL) {
        return HAL_ERROR;
    }
    
    // 检查数据长度是否有效   触觉传感器1000个字节这条限制去掉不然发不出数据
//    if (length > (PACKET_MAX_LENGTH - PACKET_HEADER_SIZE * 2)) {
//        return HAL_ERROR;  // 数据长度过长
//    }
    
    // 静态缓冲区，确保在DMA传输期间有效
    static uint8_t tx_buffer[PACKET_MAX_LENGTH];
    
    // 构建完整数据包（添加帧头和帧尾）
    // 添加帧头"das\r\n"
    memcpy(tx_buffer, PACKET_HEADER, PACKET_HEADER_SIZE);
    
    // 复制有效数据
    memcpy(&tx_buffer[PACKET_HEADER_SIZE], data, length);
    
    // 添加帧尾"das\r\n"
    memcpy(&tx_buffer[PACKET_HEADER_SIZE + length], PACKET_END, PACKET_HEADER_SIZE);
    
    uint16_t packet_length = PACKET_HEADER_SIZE + length + PACKET_HEADER_SIZE;
    
    // 等待上一次DMA传输完成
    if (HAL_UART_GetState(&huart1) == HAL_UART_STATE_BUSY_TX) {
        // 可以添加超时等待
        uint32_t timeout = HAL_GetTick();
        while (HAL_UART_GetState(&huart1) == HAL_UART_STATE_BUSY_TX) {
            if (HAL_GetTick() - timeout > 100) {  // 100ms超时
                return HAL_TIMEOUT;
            }
        }
    }
    
    // 使用HAL库的DMA发送函数
    HAL_StatusTypeDef status = HAL_UART_Transmit_DMA(&huart1, tx_buffer, packet_length);
    
    return status;
}

// 判断函数
uint8_t is_mcuid_received(const uint8_t *data, uint16_t len) 
{
    if (len != 5) return 0;
    
    if(data[0] == 'M' && 
            data[1] == 'C' && 
            data[2] == 'U' && 
            data[3] == 'I' && 
            data[4] == 'D')
		{
			return 1;
		}
		else
		{
			return 0;
		}
}


